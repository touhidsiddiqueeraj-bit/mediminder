// Optional release signing. Provide a `keystore.properties` file at the repo root
// (never committed) with: storeFile, storePassword, keyAlias, keyPassword.
// The CI release workflow creates this file from GitHub secrets when available.
val keystoreProperties = Properties().apply {
    val keystoreFile = rootProject.file("keystore.properties")
    if (keystoreFile.exists()) {
        keystoreFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile") != null

android {
    namespace = "com.mediminder.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.mediminder.app"
        minSdk = 26
        targetSdk = 35
